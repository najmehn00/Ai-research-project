        # Apply attention mask to sequence output
        sequence_output = sequence_output * attention_mask.unsqueeze(-1)

        # Additional processing
        processed_output = self.bert_processing(sequence_output)

        # Pass through optimized CNN
        logits = self.cnn(processed_output)
        return logits

