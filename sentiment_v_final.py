class InnovativeCNN(nn.Module):
    """
    نوآوری: Multi-Scale Attention CNN
    - استفاده از چندین kernel size مختلف برای capture کردن الگوهای مختلف
    - Attention mechanism روی feature maps
    - Residual connections برای بهبود gradient flow
    """
    def __init__(self, input_dim=768, num_classes=2):
        super(InnovativeCNN, self).__init__()

        # Multi-scale convolutions
        self.conv1 = nn.Conv1d(input_dim, 128, kernel_size=3, padding=1)
        self.conv2 = nn.Conv1d(input_dim, 128, kernel_size=5, padding=2)
        self.conv3 = nn.Conv1d(input_dim, 128, kernel_size=7, padding=3)

        # Attention mechanism
        self.attention = nn.MultiheadAttention(384, num_heads=8, batch_first=True)

        # Residual connection
        self.residual_conv = nn.Conv1d(input_dim, 384, kernel_size=1)

        # Classification layers
        self.dropout = nn.Dropout(0.3)
        self.fc1 = nn.Linear(384, 128)
        self.fc2 = nn.Linear(128, num_classes)

        self.relu = nn.ReLU()
        self.layer_norm = nn.LayerNorm(384)

    def forward(self, x):
        # x shape: (batch_size, seq_len, input_dim)
        x_permuted = x.permute(0, 2, 1)  # (batch_size, input_dim, seq_len)

        # Multi-scale convolutions
        conv1_out = self.relu(self.conv1(x_permuted))  # (batch_size, 128, seq_len)
        conv2_out = self.relu(self.conv2(x_permuted))  # (batch_size, 128, seq_len)
        conv3_out = self.relu(self.conv3(x_permuted))  # (batch_size, 128, seq_len)

        # Concatenate multi-scale features
        multi_scale = torch.cat([conv1_out, conv2_out, conv3_out], dim=1)  # (batch_size, 384, seq_len)
        multi_scale = multi_scale.permute(0, 2, 1)  # (batch_size, seq_len, 384)

        # Self-attention
        attended, _ = self.attention(multi_scale, multi_scale, multi_scale)

        # Residual connection
        residual = self.residual_conv(x_permuted).permute(0, 2, 1)  # (batch_size, seq_len, 384)
        output = self.layer_norm(attended + residual)

        # Global average pooling
        pooled = torch.mean(output, dim=1)  # (batch_size, 384)

        # Classification
        x = self.dropout(pooled)
        x = self.relu(self.fc1(x))
        x = self.dropout(x)
        x = self.fc2(x)

        return x

