# --- Revolutionary CNN Architecture ---

class RevolutionaryCNN(nn.Module):
    """
    نوآوری‌های جدید:
    1. Multi-Head Multi-Scale Attention
    2. Gated Convolutional Units
    3. Progressive Feature Extraction
    4. Advanced Regularization
    """
    def __init__(self, input_dim=768, num_classes=2, dropout_rate=0.2):
        super(RevolutionaryCNN, self).__init__()

        # Progressive multi-scale convolutions
        self.conv_layers = nn.ModuleList([
            nn.Conv1d(input_dim, 256, kernel_size=k, padding=k//2)
            for k in [3, 5, 7, 9]
        ])

        # Gated Linear Units for each conv layer
        self.glu_layers = nn.ModuleList([
            nn.Conv1d(256, 512, kernel_size=1) for _ in range(4)
        ])

        # Multi-head attention for different scales
        self.multi_head_attention = nn.ModuleList([
            nn.MultiheadAttention(256, num_heads=8, batch_first=True, dropout=dropout_rate)
            for _ in range(4)
        ])

        # Feature fusion
        self.feature_fusion = nn.Conv1d(1024, 512, kernel_size=1)

        # Self-attention for global context
        self.global_attention = nn.MultiheadAttention(512, num_heads=16, batch_first=True, dropout=dropout_rate)

        # Advanced pooling
        self.adaptive_pool = nn.AdaptiveAvgPool1d(1)
        self.adaptive_max_pool = nn.AdaptiveMaxPool1d(1)

        # Classification head with residual connections
        self.classifier = nn.Sequential(
            nn.Linear(1024, 512),
            nn.LayerNorm(512),
            nn.ReLU(),
            nn.Dropout(dropout_rate),

            nn.Linear(512, 256),
            nn.LayerNorm(256),
            nn.ReLU(),
            nn.Dropout(dropout_rate),

            nn.Linear(256, 128),
            nn.LayerNorm(128),
            nn.ReLU(),
            nn.Dropout(dropout_rate/2),

            nn.Linear(128, num_classes)
        )

        self.dropout = nn.Dropout(dropout_rate)
        self.layer_norm = nn.LayerNorm(512)

    def gated_conv(self, x, conv_layer, glu_layer):
        """Gated Convolutional Unit"""
        conv_out = conv_layer(x)
        glu_out = glu_layer(conv_out)

        # Split for gating
        gate, signal = glu_out.chunk(2, dim=1)
        gate = torch.sigmoid(gate)

        return gate * signal

    def forward(self, x):
        # x shape: (batch_size, seq_len, input_dim)
        x_permuted = x.permute(0, 2, 1)  # (batch_size, input_dim, seq_len)

        # Multi-scale gated convolutions with attention
        scale_features = []

        for conv_layer, glu_layer, attention in zip(self.conv_layers, self.glu_layers, self.multi_head_attention):
            # Gated convolution
            conv_out = self.gated_conv(x_permuted, conv_layer, glu_layer)
            conv_out = conv_out.permute(0, 2, 1)  # Back to (batch_size, seq_len, features)

            # Scale-specific attention
            attended, _ = attention(conv_out, conv_out, conv_out)
            scale_features.append(attended.permute(0, 2, 1))  # Back to conv format

        # Concatenate multi-scale features
        multi_scale = torch.cat(scale_features, dim=1)  # (batch_size, 1024, seq_len)

        # Feature fusion
        fused = F.relu(self.feature_fusion(multi_scale))  # (batch_size, 512, seq_len)
        fused = fused.permute(0, 2, 1)  # (batch_size, seq_len, 512)

        # Global self-attention
        global_context, _ = self.global_attention(fused, fused, fused)
        global_context = self.layer_norm(global_context + fused)  # Residual connection

        # Advanced pooling
        global_context = global_context.permute(0, 2, 1)  # (batch_size, 512, seq_len)
        avg_pooled = self.adaptive_pool(global_context).squeeze(-1)  # (batch_size, 512)
        max_pooled = self.adaptive_max_pool(global_context).squeeze(-1)  # (batch_size, 512)

        # Combine pooling strategies
        pooled = torch.cat([avg_pooled, max_pooled], dim=1)  # (batch_size, 1024)

        # Classification
        output = self.classifier(pooled)

        return output

