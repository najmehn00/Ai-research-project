class EnhancedArabicSentimentDataset(Dataset):
    def __init__(self, texts, labels, tokenizer, max_length=200, augment=False):
        self.texts = texts
        self.labels = labels
        self.tokenizer = tokenizer
        self.max_length = max_length
        self.augment = augment

    def __len__(self):
        return len(self.texts)

    def augment_text(self, text):
        """Data augmentation for Arabic text"""
        if not self.augment or np.random.random() > 0.4:
            return text

        words = text.split()
        if len(words) < 3:
            return text

        # Random word dropout (10-15% of words)
        dropout_rate = np.random.uniform(0.1, 0.15)
        num_words_to_drop = max(1, int(dropout_rate * len(words)))

        if num_words_to_drop < len(words):
            drop_indices = np.random.choice(len(words), num_words_to_drop, replace=False)
            words = [words[i] for i in range(len(words)) if i not in drop_indices]

        return ' '.join(words)

    def __getitem__(self, idx):
        text = str(self.texts[idx])

        if self.augment:
            text = self.augment_text(text)

        encoding = self.tokenizer(
            text,
            truncation=True,
            padding='max_length',
            max_length=self.max_length,
            return_tensors='pt',
            add_special_tokens=True
        )

        return {
            'input_ids': encoding['input_ids'].flatten(),
            'attention_mask': encoding['attention_mask'].flatten(),
            'label': torch.tensor(self.labels[idx], dtype=torch.long)
        }

# --- Highly Optimized CNN Architecture ---

class SuperOptimizedCNN(nn.Module):
    """
    نسخه بهینه شده با تمرکز بر دقت بالا:
    - Multi-Scale Feature Extraction با کرنل‌های بیشتر
    - Squeeze-and-Excitation Attention
    - Dense Connections
    - Advanced Regularization
    """
    def __init__(self, input_dim=768, num_classes=2, dropout_rate=0.1):
        super(SuperOptimizedCNN, self).__init__()

        # Multi-scale convolutions with consistent padding
        self.conv_layers = nn.ModuleList([
            nn.Conv1d(input_dim, 256, kernel_size=k, padding=k//2, padding_mode='zeros')
            for k in [3, 5, 7, 9, 11, 13]  # 6 different scales with odd numbers
        ])

        # Squeeze-and-Excitation blocks for each conv layer
        self.se_blocks = nn.ModuleList([
            nn.Sequential(
                nn.AdaptiveAvgPool1d(1),
                nn.Conv1d(256, 64, 1),
                nn.ReLU(),
                nn.Conv1d(64, 256, 1),
                nn.Sigmoid()
            ) for _ in range(6)
        ])

        # Dense connections
        total_features = 256 * 6  # 1536

        # Multi-head attention for feature integration
        self.feature_attention = nn.MultiheadAttention(
            total_features, num_heads=16, batch_first=True, dropout=dropout_rate
        )

        # Global context modeling
        self.global_context = nn.MultiheadAttention(
            total_features, num_heads=12, batch_first=True, dropout=dropout_rate
        )

        # Advanced pooling strategies
        self.adaptive_avg_pool = nn.AdaptiveAvgPool1d(1)
        self.adaptive_max_pool = nn.AdaptiveMaxPool1d(1)

        # Classification head with dense connections
        self.classifier = nn.Sequential(
            # First dense block
            nn.Linear(total_features * 2, 1024),  # *2 for avg+max pooling
            nn.LayerNorm(1024),
            nn.ReLU(),
            nn.Dropout(dropout_rate),

            # Second dense block
            nn.Linear(1024, 512),
            nn.LayerNorm(512),
            nn.ReLU(),
            nn.Dropout(dropout_rate),

            # Third dense block
            nn.Linear(512, 256),
            nn.LayerNorm(256),
            nn.ReLU(),
            nn.Dropout(dropout_rate/2),

            # Output layer
            nn.Linear(256, num_classes)
        )

        self.dropout = nn.Dropout(dropout_rate)
        self.layer_norm = nn.LayerNorm(total_features)

    def forward(self, x):
        # x shape: (batch_size, seq_len, input_dim)
        batch_size, seq_len, _ = x.size()
        x_permuted = x.permute(0, 2, 1)  # (batch_size, input_dim, seq_len)

        # Multi-scale feature extraction with SE attention
        scale_features = []
        target_seq_len = None

        for i, (conv_layer, se_block) in enumerate(zip(self.conv_layers, self.se_blocks)):
            # Convolution
            conv_out = F.relu(conv_layer(x_permuted))  # (batch_size, 256, seq_len)

            # Set target sequence length from first convolution
            if target_seq_len is None:
                target_seq_len = conv_out.size(2)

            # Ensure all convolutions have the same sequence length
            if conv_out.size(2) != target_seq_len:
                if conv_out.size(2) > target_seq_len:
                    conv_out = conv_out[:, :, :target_seq_len]
                else:
                    padding = target_seq_len - conv_out.size(2)
                    conv_out = F.pad(conv_out, (0, padding))

            # Squeeze-and-Excitation attention
            se_weight = se_block(conv_out)
            conv_out = conv_out * se_weight

            scale_features.append(conv_out)

        # Concatenate all scale features
        multi_scale = torch.cat(scale_features, dim=1)  # (batch_size, 1536, seq_len)
        multi_scale = multi_scale.permute(0, 2, 1)  # (batch_size, seq_len, 1536)

        # Feature-level attention
        attended_features, _ = self.feature_attention(multi_scale, multi_scale, multi_scale)
        attended_features = self.layer_norm(attended_features + multi_scale)  # Residual

        # Global context modeling
        global_context, _ = self.global_context(attended_features, attended_features, attended_features)
        global_context = global_context + attended_features  # Another residual

        # Advanced pooling
        global_context = global_context.permute(0, 2, 1)  # Back to conv format
        avg_pooled = self.adaptive_avg_pool(global_context).squeeze(-1)  # (batch_size, 1536)
        max_pooled = self.adaptive_max_pool(global_context).squeeze(-1)  # (batch_size, 1536)

        # Combine pooling strategies
        pooled = torch.cat([avg_pooled, max_pooled], dim=1)  # (batch_size, 3072)

        # Classification
        output = self.classifier(pooled)

        return output

